// Helper function to get the current hourly slogan
window.getEkvsHourlySlogan = function(offsetHours = 0) {
  if (!window.EKVS_SLOGANS || window.EKVS_SLOGANS.length === 0) {
    return "Stop scrolling, start chewing!";
  }
  const currentHourEpoch = Math.floor(Date.now() / (1000 * 60 * 60)) + offsetHours;
  // Use a deterministic scramble for maximum hourly variety across days
  const index = Math.abs(currentHourEpoch) % window.EKVS_SLOGANS.length;
  return {
    slogan: window.EKVS_SLOGANS[index],
    index: index,
    total: window.EKVS_SLOGANS.length,
    hourEpoch: currentHourEpoch
  };
};
